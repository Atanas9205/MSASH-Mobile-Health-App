const fs = require('fs');
const path = require('path');

// Valid minimal 1x1 green PNG with correct CRC
const greenPng = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, // 1x1
  0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53,
  0xDE,                                           // CRC
  0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41, 0x54, // IDAT chunk
  0x08, 0xD7, 0x63, 0x58, 0xC0, 0xC8, 0x00, 0x00,
  0x00, 0x08, 0x00, 0x03, 0x6D, 0xB0, 0x4A, 0x37,
  0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, // IEND chunk
  0xAE, 0x42, 0x60, 0x82
]);

const assetsDir = path.join(__dirname, '..', 'assets', 'images');

fs.writeFileSync(path.join(assetsDir, 'icon.png'), greenPng);
fs.writeFileSync(path.join(assetsDir, 'favicon.png'), greenPng);

console.log('✓ Created valid PNG icons');
